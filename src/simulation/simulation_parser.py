"""
SiliconPilot AI - Simulation Parser Module
Parses AC, Transient, and DC Operating Point simulation outputs generated by ngspice.
Validates vectors for non-emptiness, finiteness (no NaN/Inf), and monotonicity.
"""

import os
from dataclasses import dataclass
from typing import Optional, Tuple
import numpy as np

from src.utils.logger import get_logger

logger = get_logger("src.simulation.simulation_parser")


@dataclass
class ACSimulationData:
    """Container for parsed AC frequency response data."""
    frequencies: np.ndarray  # Frequency array in Hz
    gain_db: np.ndarray      # Voltage gain in dB
    phase_deg: np.ndarray    # Phase in degrees (-180 to +180 or unwrapped)
    is_valid: bool = True
    has_phase: bool = True
    error_message: Optional[str] = None


@dataclass
class TranSimulationData:
    """Container for parsed Transient time-domain data."""
    time_s: np.ndarray       # Time array in seconds
    vin_v: np.ndarray        # Input voltage in Volts
    vout_v: np.ndarray       # Output voltage in Volts
    is_valid: bool = True
    error_message: Optional[str] = None


class SimulationParser:
    """
    Parses vector files and logs produced by ngspice simulation runs.
    Enforces strict data integrity: checks for NaN/Inf, empty files, and monotonicity.
    """

    def __init__(self):
        pass

    def parse_ac_file(self, file_path: Optional[str]) -> ACSimulationData:
        """
        Parses an AC simulation vector output file (from wrdata).
        Expected format: freq, gain_db, freq, phase (radians or degrees).

        Returns:
            ACSimulationData with frequencies (Hz), gain_db (dB), and phase_deg (deg).
        """
        if not file_path or not os.path.exists(file_path):
            return ACSimulationData(
                frequencies=np.array([]),
                gain_db=np.array([]),
                phase_deg=np.array([]),
                is_valid=False,
                error_message="AC data file does not exist or path is None.",
            )

        if os.path.getsize(file_path) == 0:
            return ACSimulationData(
                frequencies=np.array([]),
                gain_db=np.array([]),
                phase_deg=np.array([]),
                is_valid=False,
                error_message="AC data file is empty (0 bytes).",
            )

        freqs = []
        gains = []
        phases = []
        has_phase = True

        try:
            with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    parts = line.strip().split()
                    if len(parts) >= 2:
                        try:
                            f_val = float(parts[0])
                            g_val = float(parts[1])
                            if len(parts) >= 4:
                                p_val = float(parts[3])
                                phases.append(p_val)
                            else:
                                has_phase = False

                            freqs.append(f_val)
                            gains.append(g_val)
                        except ValueError:
                            continue

            if len(phases) != len(freqs):
                has_phase = False

            if len(freqs) < 2:
                return ACSimulationData(
                    frequencies=np.array(freqs),
                    gain_db=np.array(gains),
                    phase_deg=np.array(phases) if has_phase else np.array([]),
                    is_valid=False,
                    has_phase=has_phase,
                    error_message=f"Insufficient AC data points ({len(freqs)} < 2) in file.",
                )

            freq_arr = np.array(freqs)
            gain_arr = np.array(gains)
            phase_arr = np.array(phases) if has_phase else np.array([])

            # Validate finiteness (Reject NaN and Inf)
            phase_finite = np.all(np.isfinite(phase_arr)) if has_phase else True
            if not (np.all(np.isfinite(freq_arr)) and np.all(np.isfinite(gain_arr)) and phase_finite):
                return ACSimulationData(
                    frequencies=freq_arr,
                    gain_db=gain_arr,
                    phase_deg=phase_arr,
                    is_valid=False,
                    has_phase=has_phase,
                    error_message="AC simulation vectors contain non-finite values (NaN or Inf).",
                )

            # Validate positive frequencies
            if np.any(freq_arr <= 0):
                return ACSimulationData(
                    frequencies=freq_arr,
                    gain_db=gain_arr,
                    phase_deg=phase_arr,
                    is_valid=False,
                    has_phase=has_phase,
                    error_message="AC frequency vector contains non-positive values (≤0 Hz).",
                )

            # Validate monotonic frequency ordering
            if np.any(np.diff(freq_arr) <= 0):
                return ACSimulationData(
                    frequencies=freq_arr,
                    gain_db=gain_arr,
                    phase_deg=phase_arr,
                    is_valid=False,
                    has_phase=has_phase,
                    error_message="AC frequency vector is not strictly monotonically increasing.",
                )

            # Auto-detect radians vs degrees
            # ngspice vp() is in radians (values between -2*pi and 2*pi)
            if has_phase and len(phase_arr) > 0:
                if np.max(np.abs(phase_arr)) <= 6.3:
                    phase_deg_arr = np.degrees(phase_arr)
                else:
                    phase_deg_arr = phase_arr
            else:
                phase_deg_arr = np.array([])

            return ACSimulationData(
                frequencies=freq_arr,
                gain_db=gain_arr,
                phase_deg=phase_deg_arr,
                is_valid=True,
                has_phase=has_phase,
            )

        except Exception as e:
            logger.error(f"Error parsing AC file {file_path}: {e}")
            return ACSimulationData(
                frequencies=np.array([]),
                gain_db=np.array([]),
                phase_deg=np.array([]),
                is_valid=False,
                error_message=f"Exception parsing AC file: {str(e)}",
            )

    def parse_tran_file(self, file_path: Optional[str]) -> TranSimulationData:
        """
        Parses a Transient simulation vector output file (from wrdata).
        Expected format: time, vin, time, vout.

        Returns:
            TranSimulationData with time_s (s), vin_v (V), and vout_v (V).
        """
        if not file_path or not os.path.exists(file_path):
            return TranSimulationData(
                time_s=np.array([]),
                vin_v=np.array([]),
                vout_v=np.array([]),
                is_valid=False,
                error_message="Transient data file does not exist or path is None.",
            )

        if os.path.getsize(file_path) == 0:
            return TranSimulationData(
                time_s=np.array([]),
                vin_v=np.array([]),
                vout_v=np.array([]),
                is_valid=False,
                error_message="Transient data file is empty (0 bytes).",
            )

        times = []
        vins = []
        vouts = []

        try:
            with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    parts = line.strip().split()
                    if len(parts) >= 2:
                        try:
                            t_val = float(parts[0])
                            vin_val = float(parts[1])
                            vout_val = float(parts[3]) if len(parts) >= 4 else vin_val

                            times.append(t_val)
                            vins.append(vin_val)
                            vouts.append(vout_val)
                        except ValueError:
                            continue

            if len(times) < 2:
                return TranSimulationData(
                    time_s=np.array(times),
                    vin_v=np.array(vins),
                    vout_v=np.array(vouts),
                    is_valid=False,
                    error_message=f"Insufficient transient data points ({len(times)} < 2) in file.",
                )

            time_arr = np.array(times)
            vin_arr = np.array(vins)
            vout_arr = np.array(vouts)

            # Validate finiteness (Reject NaN and Inf)
            if not (np.all(np.isfinite(time_arr)) and np.all(np.isfinite(vin_arr)) and np.all(np.isfinite(vout_arr))):
                return TranSimulationData(
                    time_s=time_arr,
                    vin_v=vin_arr,
                    vout_v=vout_arr,
                    is_valid=False,
                    error_message="Transient simulation vectors contain non-finite values (NaN or Inf).",
                )

            # Validate non-decreasing time
            if np.any(np.diff(time_arr) < 0):
                return TranSimulationData(
                    time_s=time_arr,
                    vin_v=vin_arr,
                    vout_v=vout_arr,
                    is_valid=False,
                    error_message="Transient time vector is not monotonically non-decreasing.",
                )

            return TranSimulationData(
                time_s=time_arr,
                vin_v=vin_arr,
                vout_v=vout_arr,
                is_valid=True,
            )

        except Exception as e:
            logger.error(f"Error parsing TRAN file {file_path}: {e}")
            return TranSimulationData(
                time_s=np.array([]),
                vin_v=np.array([]),
                vout_v=np.array([]),
                is_valid=False,
                error_message=f"Exception parsing TRAN file: {str(e)}",
            )
